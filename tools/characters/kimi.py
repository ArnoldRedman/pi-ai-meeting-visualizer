def bow(bm, center, width, height, depth=0.028, rot=None):
    """蝴蝶结：两片梯形环张开，中心另配结扣（领结、头饰、鞋结都用它）"""
    for sign in (1, -1):
        poly(bm, center, [(0, height * 0.20), (width * sign, height * 0.50),
                          (width * sign, -height * 0.50), (0, -height * 0.20)], depth, rot)


def letter_k(bm, center, size, depth=0.010, tilt=0.0):
    """字母 K：一竖加两斜，这么小的字只能用方块拼（腰间吊牌、领口徽章、头饰蝴蝶结用）

    两斜要从竖杠**中间**向右上/右下张开、末端别超过字面高度，否则会读成一个三角形；
    tilt 是整枚字母绕 Z 的倾角（贴在歪戴的蝴蝶结上时要跟着面一起转）
    """
    cx, cy, cz = center
    box(bm, (cx - size * 0.23, cy, cz), (size * 0.14, depth, size), (0, 0, tilt))
    box(bm, (cx + size * 0.07, cy, cz + size * 0.16), (size * 0.56, depth, size * 0.12), (0, -35, tilt))
    box(bm, (cx + size * 0.07, cy, cz - size * 0.16), (size * 0.56, depth, size * 0.12), (0, 35, tilt))


def crescent(bm, center, radius, thickness=0.018, depth=0.014, segments=5):
    """新月：几段小方块沿圆弧排成 C 形（低模里比两颗球互咬清楚得多）

    开口方向由弧段范围决定：缺口中心 = 起点 + 跨度/2 + 180°。跨度按 `covered = 1.26 × 跨度`
    折算出实际包角（每块方块的弧长是 1.3 倍间距），所以跨度 218° → 包角 275° → 缺口 85°。
    参考图里开口朝右下方，缺口中心 -45°（=315°），于是起点 26°、弧段走 26°～244°
    """
    cx, cy, cz = center
    arc = math.radians(218) * radius / (segments - 1)
    for index in range(segments):
        angle = 26 + 218 * index / (segments - 1)
        rad = math.radians(angle)
        taper = 1.0 - 0.45 * abs(index - (segments - 1) / 2) / ((segments - 1) / 2)
        box(bm, (cx + math.cos(rad) * radius, cy, cz + math.sin(rad) * radius),
            (arc * 1.30, depth, thickness * taper), (0, -angle - 90, 0))


