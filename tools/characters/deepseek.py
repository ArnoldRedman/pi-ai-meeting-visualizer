def bow(bm, center, width, height, depth=0.028, rot=None):
    """蝴蝶结：两片梯形环张开，中心另配结扣（做领结、头饰、裙上的装饰结）"""
    for sign in (1, -1):
        poly(bm, center, [(0, height * 0.20), (width * sign, height * 0.50),
                          (width * sign, -height * 0.50), (0, -height * 0.20)], depth, rot)


def octagon(width, height, corner=0.32):
    """圆角矩形轮廓，给围裙这种大块面切掉尖角"""
    x, z = width / 2, height / 2
    cx, cz = x * corner, z * corner
    return [(-x + cx, -z), (x - cx, -z), (x, -z + cz), (x, z - cz),
            (x - cx, z), (-x + cx, z), (-x, z - cz), (-x, -z + cz)]


def triangle(bm, points, depth, y):
    """三个 (x, z) 顶点沿 Y 挤出的薄三棱柱，专门做鲸尾鳍叶"""
    front = [bm.verts.new((x, y - depth / 2, z)) for x, z in points]
    back = [bm.verts.new((x, y + depth / 2, z)) for x, z in points]
    bm.faces.new(front)
    bm.faces.new(back[::-1])
    for i in range(3):
        j = (i + 1) % 3
        bm.faces.new([front[i], front[j], back[j], back[i]])


