def bow(bm, center, width, height, depth=0.028, rot=None):
    """蝴蝶结：两片梯形环张开，中心另配结扣（领结、头饰、鞋结都用它）"""
    for sign in (1, -1):
        poly(bm, center, [(0, height * 0.20), (width * sign, height * 0.50),
                          (width * sign, -height * 0.50), (0, -height * 0.20)], depth, rot)


def letter_z(bm, center, size, depth=0.008):
    """字母 Z：上下两横加一斜（徽章、吊牌用）"""
    cx, cy, cz = center
    box(bm, (cx, cy, cz + size * 0.42), (size, depth, size * 0.16))
    box(bm, (cx, cy, cz - size * 0.42), (size, depth, size * 0.16))
    box(bm, (cx, cy, cz), (size * 1.25, depth, size * 0.16), (0, 40, 0))


def gem(bm, center, size):
    """紫水晶吊坠：一颗压扁的八面体，够低模"""
    sphere(bm, center, size, 0, (0.8, 0.5, 1.5))


def build(builder):
    bm = builder.bm

    # 裙面装饰的统一换算：裙片带 17.4° 倾角（斜率 tan17.4° = 0.3134），越往下越靠前，
    # 每个小件都得按自己的 z 反算 y，否则会一半陷进裙片里
    def panel_y(z):
        return -0.159 - (0.200 - z) * 0.3134

    # ---------------- 腿：白色系带高跟短靴 ----------------
    for sign in (1, -1):
        bone = f'leg-{"left" if sign > 0 else "right"}'
        x = 0.0836 * sign
        with builder.part(bone, 'skin'):
            box(bm, (x, -0.004, 0.148), (0.086, 0.100, 0.086))  # 裙下小腿
        with builder.part(bone, 'cream'):
            box(bm, (x, -0.008, 0.100), (0.098, 0.114, 0.084))  # 靴筒
            box(bm, (x, -0.028, 0.032), (0.096, 0.158, 0.048))  # 鞋身
        with builder.part(bone, 'black'):
            box(bm, (x, -0.086, 0.026), (0.094, 0.056, 0.044))  # 黑鞋头
            box(bm, (x, 0.028, 0.018), (0.074, 0.072, 0.036))  # 黑鞋跟
            box(bm, (x, -0.040, 0.006), (0.100, 0.150, 0.012))  # 鞋底
            for z in (0.084, 0.114):  # 交叉系带
                box(bm, (x, -0.068, z), (0.092, 0.009, 0.010), (0, -38, 0))
                box(bm, (x, -0.068, z), (0.092, 0.009, 0.010), (0, 38, 0))

    # ---------------- 躯干：白衬衫 + 黑束腰 + 黑裙配白前裙片 ----------------
    with builder.part('torso', 'cream'):
        box(bm, (0, -0.005, 0.320), (0.262, 0.212, 0.104))  # 衬衫
        box(bm, (0, -0.020, 0.352), (0.190, 0.140, 0.036))  # 荷叶边高领
        box(bm, (0, -0.098, 0.318), (0.130, 0.034, 0.086))  # 胸前荷叶边门襟
    with builder.part('torso', 'black'):
        box(bm, (0, -0.005, 0.262), (0.268, 0.216, 0.076))  # 束腰
    with builder.part('torso', 'black'):
        slab(bm, (0, -0.005, 0.209), (0.376, 0.306), (0.286, 0.236), 0.118)  # 外裙
    with builder.part('torso', 'cream'):
        # 正面白裙片：参考图那条带几何花纹的白色前裙
        box(bm, (0, -0.146, 0.200), (0.146, 0.026, 0.136), (-17.4, 0, 0))
        slab(bm, (0, -0.005, 0.130), (0.368, 0.298), (0.376, 0.306), 0.034)  # 裙下白荷叶边
    with builder.part('torso', 'grey'):
        slab(bm, (0, -0.005, 0.104), (0.344, 0.282), (0.368, 0.298), 0.026)  # 灰色底层荷叶边
    with builder.part('torso', 'black'):
        for sign in (1, -1):
            box(bm, (0.078 * sign, -0.143, 0.200), (0.014, 0.026, 0.138), (-17.4, 0, 0))  # 裙片黑边
        # 前裙片上的几何花纹：吊坠 + 菱形排布的小方块 + 底部的倒三角旗，和参考图一个意思
        for x, z in ((0.019, 0.204), (-0.019, 0.204), (0.0, 0.186), (0.038, 0.186), (-0.038, 0.186),
                     (0.019, 0.168), (-0.019, 0.168)):
            box(bm, (x, panel_y(z), z), (0.020, 0.022, 0.020), (-17.4, 0, 0))
        box(bm, (0, panel_y(0.154), 0.154), (0.100, 0.016, 0.010), (-17.4, 0, 0))  # 旗顶横边
        for sign in (1, -1):
            box(bm, (0.025 * sign, panel_y(0.140), 0.140), (0.058, 0.016, 0.010), (-17.4, -29.2 * sign, 0))
    with builder.part('torso', 'silver'):
        # 花纹顶上挂下来的吊坠：细吊索 + 小菱形（poly 的轮廓落在 XZ 平面，跟裙片倾角天然对齐）
        box(bm, (0, panel_y(0.208), 0.208), (0.008, 0.016, 0.026), (-17.4, 0, 0))
        poly(bm, (0, panel_y(0.230), 0.230),
             [(0.016, 0.0), (0.0, 0.016), (-0.016, 0.0), (0.0, -0.016)], 0.016, (-17.4, 0, 0))
    with builder.part('torso', 'gem'):
        gem(bm, (0, panel_y(0.126), 0.126), 0.012)  # 三角旗尖上的紫水晶
    with builder.part('torso', 'silver'):
        # 束腰的银链、音乐挂饰位置换成银坠
        limb(bm, (-0.070, -0.112, 0.246), (-0.074, -0.116, 0.206), 0.007, 0.007, 6)
        sphere(bm, (-0.074, -0.118, 0.198), 0.011, 1)
        limb(bm, (0.030, -0.112, 0.248), (0.046, -0.116, 0.220), 0.006, 0.006, 6)
        box(bm, (0.070, -0.118, 0.182), (0.012, 0.012, 0.030))  # 吊牌链
    with builder.part('torso', 'black'):
        box(bm, (0.070, -0.134, 0.164), (0.054, 0.016, 0.060))  # 方形 "Z" 吊牌底板
    with builder.part('torso', 'cream'):
        letter_z(bm, (0.070, -0.144, 0.164), 0.032, 0.006)
