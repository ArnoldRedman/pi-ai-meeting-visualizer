    # 封面朝前（-Y）贴在右手掌心外侧，故意做得比手掌大（拿在手里才看得出来是本书）；
    # 书身的 x 外缘（含 -25° 转角）算到 -0.4386，仍在手掌的 -0.439 以内，
    # 横向包围盒不会变大，不会被这本书从座椅中心顶偏（scene.mjs 按包围盒中心摆人）
    book_x, book_y, book_z = -0.378, -0.095, 0.288
    book_twist = -25  # 绕 Z 外转一点：正面才看得出这是一本书（露出内侧白书页），而不是一块贴片
    book_face = -0.023  # 封面装饰层：书身前表面在 dy -0.020，装饰压在这层上露出约 7 毫米

