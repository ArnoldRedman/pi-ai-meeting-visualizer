#   1. 后发占 y ≤ 0.222，垂到腰的侧发整片留在手臂后方（y ≥ 0.086），动作时才不会穿进胳膊
#   2. 裙面上的白裙片、几何花纹、徽章都按 17.4° 的裙面倾角贴，逐层向前让 4~6 毫米
#   3. 字母徽章（这里的 "Z"）用三根细方块拼，比贴图省事，低模上反而更清楚
