    for sign in (1, -1):
        bone = f'arm-{"left" if sign > 0 else "right"}'
        with builder.part(bone, 'cream'):
            box(bm, (0.166 * sign, -0.012, 0.290), (0.164, 0.198, 0.188))  # 泡泡袖
            box(bm, (0.290 * sign, -0.012, 0.288), (0.058, 0.178, 0.168))  # 袖口荷叶边
        with builder.part(bone, 'black'):
            box(bm, (0.248 * sign, -0.012, 0.288), (0.026, 0.192, 0.182))  # 黑色滚边
        with builder.part(bone, 'skin'):
            box(bm, (0.334 * sign, -0.012, 0.288), (0.070, 0.140, 0.130))  # 前臂
            box(bm, (0.396 * sign, -0.012, 0.288), (0.086, 0.132, 0.130))  # 手掌
            box(bm, (0.360 * sign, -0.072, 0.300), (0.044, 0.048, 0.050))  # 拇指

