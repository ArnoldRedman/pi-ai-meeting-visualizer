def bow(bm, center, width, height, depth=0.028, rot=None):
    """蝴蝶结：两片梯形环张开，中心另配结扣（领结、头饰、裙上装饰结都用它）"""
    for sign in (1, -1):
        poly(bm, center, [(0, height * 0.20), (width * sign, height * 0.50),
                          (width * sign, -height * 0.50), (0, -height * 0.20)], depth, rot)


def flower(bm, center, radius, depth=0.014, petals=8, facing='front'):
    """花：一圈花瓣加金色花心，facing='front' 花面朝 -Y，'side' 花面朝 +X（戴在头侧）"""
    cx, cy, cz = center
    for index in range(petals):
        angle = index * 360 / petals
        rad = math.radians(angle)
        # 花瓣要短而胖，细长的花瓣在低模上会读成叉号
        if facing == 'front':
            box(bm, (cx + math.cos(rad) * radius * 0.60, cy, cz + math.sin(rad) * radius * 0.60),
                (radius * 0.62, depth, radius * 0.46), (0, -angle, 0))
        else:
            box(bm, (cx, cy + math.cos(rad) * radius * 0.60, cz + math.sin(rad) * radius * 0.60),
                (depth, radius * 0.62, radius * 0.46), (angle, 0, 0))


