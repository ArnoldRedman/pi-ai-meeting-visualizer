# Gemini 娘化角色：回到第一版的比例和造型，只修两处
#
# 第一版看着可爱的地方要保住：大方头、紫色发盖、猫耳、异色瞳、白紫小裙子、星星。
# 本次只修：
#   1. 手太大太长 —— 手臂缩短，手掌和拇指收小
#   2. 走路时脚和身子挤到一起 —— 靴子收窄收薄，裙摆略收，给交叉的腿留出行李缝
#
# 骨骼锚点（bind 空间，与原角色一致，不可移动）：
#   腿骨 (±0.0836, 0.0288, 0.17625)   躯干骨 (0, 0.0288, 0.17625)
#   手臂 (±0.0999, 0.01725, 0.28775)  头骨   (0, 0.00236, 0.34325)
from chibi import box, slab, sphere, star, wedge

# 第一版的配色
PALETTE = {
    'skin': (0.969, 0.859, 0.784),
    'hair': (0.365, 0.271, 0.690),
    'hair-light': (0.780, 0.608, 0.933),
    'navy': (0.165, 0.137, 0.314),
    'white': (0.961, 0.949, 0.984),
    'gold': (0.937, 0.796, 0.420),
    'trim': (0.482, 0.369, 0.847),
    'eye-pink': (0.949, 0.471, 0.706),
    'eye-amber': (0.961, 0.702, 0.235),
    'eye-dark': (0.227, 0.173, 0.388),
    'mouth': (0.659, 0.373, 0.439),
    'blush': (0.953, 0.659, 0.753),
    'sole': (0.200, 0.165, 0.400),
    'shine': (1.0, 1.0, 1.0),
}


def build(builder):
    bm = builder.bm

    # ---------------- 腿：白色过膝靴 + 紫色厚底（收窄收薄，走路不撞裙子和彼此） ----------------
    for sign in (1, -1):
        bone = f'leg-{"left" if sign > 0 else "right"}'
        x = 0.0836 * sign
        with builder.part(bone, 'white'):
            box(bm, (x, -0.008, 0.112), (0.118, 0.150, 0.142))
        with builder.part(bone, 'trim'):
            box(bm, (x, -0.004, 0.176), (0.126, 0.156, 0.038))
        with builder.part(bone, 'white'):
            box(bm, (x, -0.024, 0.056), (0.112, 0.176, 0.056))
        with builder.part(bone, 'sole'):
            box(bm, (x, -0.028, 0.014), (0.126, 0.196, 0.028))
        with builder.part(bone, 'trim'):
            star(bm, (x, -0.086, 0.132), 0.030, 0.013, 0.014)

    # ---------------- 躯干：深紫紧身上衣 + 白裙 + 猫尾 ----------------
    with builder.part('torso', 'navy'):
        box(bm, (0, -0.005, 0.275), (0.27, 0.215, 0.16))
    with builder.part('torso', 'white'):
        box(bm, (0, -0.012, 0.345), (0.285, 0.20, 0.05))
        box(bm, (0, -0.112, 0.255), (0.15, 0.02, 0.07))
    with builder.part('torso', 'gold'):
        star(bm, (0, -0.122, 0.315), 0.05, 0.022, 0.018)
    with builder.part('torso', 'trim'):
        box(bm, (0, 0, 0.225), (0.275, 0.21, 0.04))
    with builder.part('torso', 'navy'):
        box(bm, (0, 0, 0.185), (0.25, 0.195, 0.075))
    with builder.part('torso', 'white'):
        slab(bm, (0, -0.005, 0.202), (0.360, 0.290), (0.290, 0.240), 0.092)  # 裙摆略收，给腿留缝
    # 猫尾：从裙摆后面伸出后向左后上方翘起，全程避在后发（y 最大 0.2255、z 最低 0.315）之外
    with builder.part('torso', 'hair'):
        box(bm, (0.008, 0.135, 0.182), (0.076, 0.132, 0.076))
        box(bm, (0.024, 0.240, 0.240), (0.072, 0.102, 0.130))
        box(bm, (0.038, 0.278, 0.360), (0.070, 0.086, 0.130))
    with builder.part('torso', 'hair-light'):
        sphere(bm, (0.048, 0.292, 0.432), 0.045, 1)

    # ---------------- 手臂：白色泡泡袖 + 前臂 + 手套（缩短、手收小） ----------------
    for sign in (1, -1):
        bone = f'arm-{"left" if sign > 0 else "right"}'
        with builder.part(bone, 'white'):
            box(bm, (0.170 * sign, -0.012, 0.288), (0.165, 0.200, 0.185))
        with builder.part(bone, 'trim'):
            box(bm, (0.272 * sign, -0.012, 0.288), (0.042, 0.205, 0.190))
        with builder.part(bone, 'skin'):
            box(bm, (0.325 * sign, -0.012, 0.288), (0.085, 0.150, 0.130))
            box(bm, (0.385 * sign, -0.012, 0.288), (0.090, 0.130, 0.132))
        with builder.part(bone, 'skin'):
            box(bm, (0.352 * sign, -0.078, 0.300), (0.045, 0.050, 0.052))
        with builder.part(bone, 'gold'):
            star(bm, (0.170 * sign, -0.120, 0.352), 0.040, 0.018, 0.016)

    # ---------------- 头：脸、刘海、长发、双发团、猫耳、星星饰品 ----------------
    with builder.part('head', 'skin'):
        box(bm, (0, -0.028, 0.505), (0.30, 0.245, 0.30))
        box(bm, (0, -0.02, 0.352), (0.10, 0.10, 0.04))
    with builder.part('head', 'hair'):
        box(bm, (0, -0.115, 0.635), (0.335, 0.09, 0.08))
        box(bm, (0, 0.005, 0.687), (0.33, 0.30, 0.135))
        box(bm, (0, 0.152, 0.55), (0.29, 0.13, 0.42))
        box(bm, (0.152, -0.055, 0.5), (0.06, 0.21, 0.31))
        box(bm, (-0.152, -0.055, 0.5), (0.06, 0.21, 0.31))
        sphere(bm, (0.176, 0.062, 0.7), 0.078, 1)
        sphere(bm, (-0.176, 0.062, 0.7), 0.078, 1)
        wedge(bm, (0.115, -0.02, 0.7), (0.115, 0.02), 0.095, 0.09, (0, -10, 0))
        wedge(bm, (-0.115, -0.02, 0.7), (0.115, 0.02), 0.095, 0.09, (0, 10, 0))
    with builder.part('head', 'hair-light'):
        box(bm, (0, 0.168, 0.395), (0.25, 0.115, 0.16))
    with builder.part('head', 'blush'):
        wedge(bm, (0.115, -0.055, 0.7), (0.06, 0.012), 0.05, 0.045, (0, -10, 0))
        wedge(bm, (-0.115, -0.055, 0.7), (0.06, 0.012), 0.05, 0.045, (0, 10, 0))
        box(bm, (0.118, -0.152, 0.462), (0.055, 0.012, 0.032))
        box(bm, (-0.118, -0.152, 0.462), (0.055, 0.012, 0.032))
    with builder.part('head', 'gold'):
        star(bm, (0.152, -0.148, 0.67), 0.058, 0.026, 0.022)
    with builder.part('head', 'white'):
        star(bm, (-0.085, -0.155, 0.628), 0.034, 0.015, 0.018)
    # 异色瞳：左粉、右琥珀，各带一个高光点
    for sign in (1, -1):
        with builder.part('head', 'eye-dark'):
            box(bm, (0.062 * sign, -0.152, 0.505), (0.082, 0.014, 0.095))
        with builder.part('head', 'eye-pink' if sign > 0 else 'eye-amber'):
            box(bm, (0.062 * sign, -0.158, 0.502), (0.058, 0.012, 0.07))
        with builder.part('head', 'shine'):
            box(bm, (0.075 * sign, -0.163, 0.523), (0.022, 0.010, 0.024))
    with builder.part('head', 'mouth'):
        box(bm, (0, -0.152, 0.432), (0.05, 0.014, 0.02))
