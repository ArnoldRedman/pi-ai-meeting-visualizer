def octagon(width, height, corner=0.38):
    x, z = width / 2, height / 2
    cx, cz = x * corner, z * corner
    return [(-x + cx, -z), (x - cx, -z), (x, -z + cz), (x, z - cz),
            (x - cx, z), (-x + cx, z), (-x, z - cz), (-x, -z + cz)]


def membrane(bm, points, y, thickness=0.020):
    """若干 (x, z) 顶点围成的薄翼面，自动取重心"""
    cx = sum(point[0] for point in points) / len(points)
    cz = sum(point[1] for point in points) / len(points)
    poly(bm, (cx, y, cz), [(x - cx, z - cz) for x, z in points], thickness)


